const WTP_LANG_OPTIONS = [
  { code: 'en', name: 'English' },
  { code: 'zh', name: '中文' },
  { code: 'ja', name: '日本語' },
  { code: 'ko', name: '한국어' },
  { code: 'fr', name: 'Français' },
  { code: 'de', name: 'Deutsch' },
  { code: 'es', name: 'Español' },
  { code: 'ru', name: 'Русский' },
  { code: 'ar', name: 'العربية' }
];

function wtpGetStrings(locale) {
  return WTP_STRINGS[locale === 'zh' ? 'zh' : 'en'] || WTP_STRINGS.en;
}

function wtpBilingual(key) {
  const zh = WTP_STRINGS.zh[key];
  const en = WTP_STRINGS.en[key];
  if (!zh || !en) return zh || en || key;
  return `${zh} / ${en}`;
}

function wtpApplyI18n(root, locale) {
  const s = wtpGetStrings(locale);
  root.querySelectorAll('[data-i18n-btn]').forEach((el) => {
    const key = el.getAttribute('data-i18n-btn');
    if (key) el.textContent = wtpBilingual(key);
  });
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (s[key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = s[key];
      } else if (el.tagName !== 'BUTTON') {
        el.textContent = s[key];
      }
    }
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const key = el.getAttribute('data-i18n-title');
    if (s[key]) el.title = s[key];
  });
  return s;
}

if (typeof globalThis !== 'undefined') {
  globalThis.wtpGetStrings = wtpGetStrings;
  globalThis.wtpBilingual = wtpBilingual;
  globalThis.wtpApplyI18n = wtpApplyI18n;
  globalThis.WTP_LANG_OPTIONS = WTP_LANG_OPTIONS;
  globalThis.WTP_STRINGS = WTP_STRINGS;
}
